using System.IO;
using System.Linq;
using System.Text;
using ClassDiagramGenerator.Application;
using ClassDiagramGenerator.Infrastructure.Export;
using ClassDiagramGenerator.Infrastructure.Parsing;
using Unity.Pipeline.Commands;

namespace EmpireAtWar.Editor.Diagrams
{
    // Agent entry points: unity command diagram_generate | diagram_render | diagram_open.
    public static class DiagramCliCommands
    {
        private const string APPROXIMATE_NOTE = "' Generated by diagram_generate (regex parser): partial classes and nested types may be incomplete.";

        [CliCommand("diagram_generate", "Scans C# folders or files into a PlantUML class diagram under Logs/Diagrams/<name> and renders SVG + PNG locally.")]
        public static object Generate(
            [CliArg("paths", "Folders or .cs files relative to the project root, separated by ',' or ';'.")] string paths,
            [CliArg("name", "Diagram name: letters, digits, '_' or '-'. Output goes to Logs/Diagrams/<name>/.")] string name,
            [CliArg("associations", "Draw field, property, parameter and call associations between types.")] bool associations = true,
            [CliArg("open", "Viewer after rendering: none, rider, editor or browser.")] string open = "none")
        {
            DiagramOpenTarget target = DiagramOpener.Parse(open);
            string puml = DiagramOutputPaths.Puml(name);
            var scripts = DiagramSourceCollector.Collect(DiagramSourceCollector.Split(paths));

            var service = new DiagramGenerationService(new RegexClassDiagramParser(), new PlantUmlExporter());
            GenerateDiagramResult result = service.Generate(new GenerateDiagramRequest
            {
                SelectedScriptPaths = scripts,
                IncludeAssociations = associations
            });
            if (!result.Success)
                throw new System.InvalidOperationException($"{result.StatusMessage} {string.Join("; ", result.Warnings)}".Trim());

            Directory.CreateDirectory(DiagramOutputPaths.Folder(name));
            File.WriteAllText(puml, APPROXIMATE_NOTE + "\n" + result.PlantUmlText, new UTF8Encoding(false));
            PlantUmlRenderer.Render(puml);
            DiagramOpener.Open(name, target);

            return new
            {
                name,
                puml,
                svg = DiagramOutputPaths.Svg(name),
                png = DiagramOutputPaths.Png(name),
                scriptCount = scripts.Count,
                typeCount = result.TypeCount,
                warnings = result.Warnings.ToArray()
            };
        }

        [CliCommand("diagram_render", "Renders an existing .puml (any diagram type) to SVG + PNG under Logs/Diagrams/<file name>/.")]
        public static object Render(
            [CliArg("puml", "Path to a .puml file. Files outside Logs/Diagrams/<name>/ are copied there first.")] string puml,
            [CliArg("open", "Viewer after rendering: none, rider, editor or browser.")] string open = "none")
        {
            DiagramOpenTarget target = DiagramOpener.Parse(open);
            if (!File.Exists(puml))
                throw new FileNotFoundException($"Diagram source not found: {puml}", puml);

            string name = Path.GetFileNameWithoutExtension(puml);
            string destination = DiagramOutputPaths.Puml(name);
            if (Path.GetFullPath(puml) != Path.GetFullPath(destination))
            {
                Directory.CreateDirectory(DiagramOutputPaths.Folder(name));
                File.Copy(puml, destination, true);
            }

            PlantUmlRenderer.Render(destination);
            DiagramOpener.Open(name, target);
            return new { name, puml = destination, svg = DiagramOutputPaths.Svg(name), png = DiagramOutputPaths.Png(name) };
        }

        [CliCommand("diagram_open", "Opens a rendered diagram from Logs/Diagrams/<name>/ in Rider, the Editor preview window or the browser.")]
        public static object Open(
            [CliArg("name", "Diagram name under Logs/Diagrams.")] string name,
            [CliArg("target", "Viewer: rider, editor or browser.")] string target = "editor")
        {
            DiagramOpenTarget parsed = DiagramOpener.Parse(target);
            if (!File.Exists(DiagramOutputPaths.Puml(name)))
                throw new FileNotFoundException($"No diagram named '{name}' under {DiagramOutputPaths.ROOT}.", DiagramOutputPaths.Puml(name));
            DiagramOpener.Open(name, parsed);
            return new { name, target = parsed.ToString().ToLowerInvariant() };
        }
    }
}
